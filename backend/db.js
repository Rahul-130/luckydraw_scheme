const oracledb = require('oracledb');

oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;
oracledb.fetchAsString = [oracledb.CLOB]; // Automatically fetch CLOBs as strings

let pool;
async function getPool() {
  if (pool) return pool;

  const isProduction = process.env.NODE_ENV === 'production';
  let user, password, connectString, configDir, walletLocation, walletPassword;
  const poolAttributes = {
    poolMin: 1,
    poolMax: 30,
    poolIncrement: 1,
    externalAuth: false, // Explicitly set for clarity, usually false for user/password
  };

  if (isProduction) {
    console.log(`[DB] Attempting to connect to Oracle Cloud DB....`);
    user = process.env.ORACLE_CLOUD_USER;
    password = process.env.ORACLE_CLOUD_PASSWORD;
    connectString = process.env.ORACLE_CLOUD_STRING;

    // Conditionally add wallet properties if they exist
    if (process.env.ORACLE_CLOUD_WALLET_PATH) {
      poolAttributes.configDir = process.env.ORACLE_CLOUD_WALLET_PATH;
      poolAttributes.walletLocation = process.env.ORACLE_CLOUD_WALLET_PATH;
    }
    if (process.env.ORACLE_CLOUD_WALLET_PASSWORD) {
      poolAttributes.walletPassword = process.env.ORACLE_CLOUD_WALLET_PASSWORD;
    }

    console.log(`[DB-PROD] User: ${user}, Connect String: ${connectString}, Wallet Path: ${process.env.ORACLE_CLOUD_WALLET_PATH || 'N/A'}`);
  } else {
    console.log(`[DB] Attempting to connect to local/docker Oracle DB...`);
    user = process.env.ORACLE_USER;
    password = process.env.ORACLE_PASSWORD;
    connectString = `${process.env.ORACLE_HOST}:${process.env.ORACLE_PORT}/${process.env.ORACLE_SERVICE_NAME}`;

    console.log(`[DB-DEV] User: ${user}, Connect String: ${connectString}`);
  }

  try {
    pool = await oracledb.createPool({
      user,
      password,
      connectString,
    ...poolAttributes,
    // Adding a pool alias helps identify the connection in shared environments
    poolAlias: isProduction ? 'PROD_POOL' : 'DEV_POOL'
    });
  
    console.log(`[DB] Connection pool created successfully for ${isProduction ? 'production' : 'development'}.`);
  } catch (err) {
    console.error(`[DB-ERROR] Failed to create connection pool for ${isProduction ? 'production' : 'development'}:`, err.message);
    throw err; // Re-throw to prevent server from starting with a bad DB connection
  }
  return pool;
}
async function getConnection() {
  const p = await getPool();
  return p.getConnection();
}
async function initSchema() {
  const conn = await getConnection();
  try {
    await conn.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE users (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR2(255) NOT NULL,
      phone VARCHAR2(20) NOT NULL,
      email VARCHAR2(255) UNIQUE NOT NULL,
      password_hash VARCHAR2(255) NOT NULL,
      is_2fa_enabled NUMBER(1) DEFAULT 0 NOT NULL,
      two_fa_secret VARCHAR2(255),
      two_fa_recovery_codes CLOB,
      user_role VARCHAR2(50) DEFAULT ''admin'' NOT NULL,
      user_parent_id NUMBER,
      company_name VARCHAR2(255),
      company_address VARCHAR2(500),
      company_cell VARCHAR2(20),
      company_phone VARCHAR2(20)
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);

    await conn.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE books (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      owner_id NUMBER NOT NULL,
      name VARCHAR2(255) NOT NULL,
      max_customers NUMBER NOT NULL,
      total_amount NUMBER DEFAULT 0,
      is_active NUMBER(1) DEFAULT 1 NOT NULL,
      start_month_iso VARCHAR2(7) NOT NULL,
      CONSTRAINT fk_books_owner FOREIGN KEY (owner_id) REFERENCES users(id)
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);


    await conn.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE customers (
      id NUMBER NOT NULL,
      book_id NUMBER NOT NULL,
      name VARCHAR2(255) NOT NULL,
      relation_info VARCHAR2(255),
      phone varchar2(255) NOT NULL,
      address VARCHAR2(255) NOT NULL,
      is_frozen NUMBER(1) DEFAULT 0 NOT NULL,
      settled_date TIMESTAMP WITH TIME ZONE,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
      bonus_amount NUMBER DEFAULT 0,
      settlement_receipt_no VARCHAR2(255),
      settlement_agent_name VARCHAR2(255),
      CONSTRAINT pk_customers PRIMARY KEY (id, book_id),
      CONSTRAINT fk_customers_book FOREIGN KEY (book_id) REFERENCES books(id)
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);


    await conn.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE payments (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id NUMBER NOT NULL,
      book_id NUMBER NOT NULL,
      month_iso VARCHAR2(7) NOT NULL,
      amount NUMBER NOT NULL,
      amount_cash NUMBER DEFAULT 0,
      amount_online NUMBER DEFAULT 0,
      amount_instore NUMBER DEFAULT 0,
      payment_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
      receipt_no VARCHAR2(255),
      payment_type VARCHAR2(50) NOT NULL,
      agent_name VARCHAR2(255),
      is_luckydraw_winner NUMBER(1) DEFAULT 0 NOT NULL,
      CONSTRAINT fk_payments_book FOREIGN KEY (book_id) REFERENCES books(id),
      CONSTRAINT fk_payments_customer FOREIGN KEY (customer_id, book_id) REFERENCES customers(id, book_id),
      CONSTRAINT uq_payments_customer_book_month UNIQUE (customer_id, book_id, month_iso)
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);


    await conn.execute(`BEGIN EXECUTE IMMEDIATE 'CREATE TABLE winner (
      id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      book_id NUMBER NOT NULL,
      book_name VARCHAR2(255),
      customer_id NUMBER NOT NULL,
      customer_name VARCHAR2(255),
      relation_info VARCHAR2(255),
      address VARCHAR2(255),
      phone VARCHAR2(50),
      is_manual NUMBER(1) DEFAULT 0 NOT NULL,
      win_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT fk_winner_book FOREIGN KEY (book_id) REFERENCES books(id) ON DELETE CASCADE,
      CONSTRAINT fk_winner_customer FOREIGN KEY (customer_id, book_id) REFERENCES customers(id, book_id) ON DELETE CASCADE
    )'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;`);


    await conn.commit();
  } finally { await conn.close(); }
}
module.exports = { getConnection, initSchema, oracledb };